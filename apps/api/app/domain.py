def today() -> date:
    return utcnow().date()


def intern_day(start_date: date, day_offset: int = 0, on: date | None = None) -> int:
    return ((on or today()) - start_date).days + 1 + day_offset


def stage_for_day(day: int) -> Stage:
    for stage in STAGES:
        if stage.start <= day <= stage.end:
            return stage
    return STAGES[-1]  # pragma: no cover


def total_days(program_months: int) -> int:
    return TOTAL_DAYS.get(program_months, program_months * 30)
